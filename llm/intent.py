import json
import re
from enum import Enum

from llm.client import complete

INTENT_MODEL = "anthropic/claude-haiku-4.5"

SYSTEM_PROMPT = """Ты определяешь намерение пользователя личного ИИ-ассистента в \
свободном сообщении: хочет ли он поставить задачу/напоминание ("task"), сообщает \
что-то про деньги ("finance"), просит подготовить документ/письмо/таблицу \
("document"), просит переслать сообщение другому пользователю по @username \
("relay") или просто делится мыслью, договорённостью, вопросом — общается в \
свободной форме ("chat").

Признаки task: явная или подразумеваемая просьба напомнить, не забыть, сделать \
что-то к сроку или регулярно ("напомни...", "не забыть...", "каждый день...", \
"завтра нужно...", "через час..."). Если срока или повторения нет — это chat, даже \
если сообщение про дела.

Признаки finance: сообщение о трате или поступлении денег ("потратила 500...", \
"получил зарплату..."), о текущем остатке на счёте/балансе ("у меня осталось \
3000", "баланс 5000"), или просьба предупреждать при низком балансе \
("предупреждай, если останется меньше 2000"). Если сообщение просто про деньги в \
общем смысле, без конкретной суммы или остатка (например, обсуждение бюджета \
абстрактно) — это chat, а не finance.

Признаки document: явная просьба написать/составить/подготовить письмо, документ, \
договор, заявление, таблицу, смету, счёт ("напиши письмо клиенту...", "составь \
договор на...", "сделай таблицу расходов за..."). Если это просто рассуждение о \
документе без просьбы его составить — это chat, а не document.

Признаки relay: явная просьба передать/переслать/написать конкретному человеку, \
указанному через @username ("передай @ivan_petrov, что...", "напиши @maria_k, \
что встреча переносится"). Без явного @username в тексте — это не relay, даже \
если упомянуто имя без username.

Ответь строго JSON без пояснений и без markdown-разметки, в формате:
{"intent": "task" | "finance" | "document" | "relay" | "chat"}"""

_JSON_BLOCK_RE = re.compile(r"\{.*\}", re.DOTALL)


class Intent(str, Enum):
    task = "task"
    finance = "finance"
    document = "document"
    relay = "relay"
    chat = "chat"


def _extract_json(raw: str) -> dict:
    match = _JSON_BLOCK_RE.search(raw)
    if match is None:
        raise ValueError(f"Не удалось найти JSON в ответе модели: {raw!r}")
    return json.loads(match.group(0))


async def detect_intent(text: str) -> Intent:
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": text},
    ]
    raw = await complete(messages, model=INTENT_MODEL)
    data = _extract_json(raw)
    return Intent(data["intent"])
